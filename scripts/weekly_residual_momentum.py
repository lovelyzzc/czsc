REPO_ROOT = SCRIPT_DIR.parent
PROTOCOL_PATH = SCRIPT_DIR / "weekly_residual_momentum_protocol_2026-08-12.json"
OUTPUT_DIR = SCRIPT_DIR / "_output" / "weekly_residual_momentum"
