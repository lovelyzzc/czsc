assert CORE_SPEC and CORE_SPEC.loader
core = importlib.util.module_from_spec(CORE_SPEC)
CORE_SPEC.loader.exec_module(core)


def sha256_file(path: Path) -> str:
    """Return a streaming SHA256 digest."""

    digest = hashlib.sha256()
    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _resolve(locator: str) -> Path:
    path = Path(locator).expanduser()
    return path if path.is_absolute() else REPO_ROOT / path


def load_and_verify_protocol() -> dict[str, Any]:
    """Load the protocol and bind the source data plus genesis audit."""

    protocol = json.loads(PROTOCOL_PATH.read_text(encoding="utf-8"))
    if protocol.get("schema") != "weekly_residual_momentum_protocol_v1":
        raise RuntimeError("unexpected residual-momentum protocol schema")
    if protocol.get("live_trading_authorized") is not False:
        raise RuntimeError("retrospective protocol must not authorize live trading")
    for name in ("ranked_surface", "price_panel", "genesis_audit"):
        record = protocol["inputs"][name]
        actual = sha256_file(_resolve(record["path"]))
        if actual != record["sha256"]:
            raise RuntimeError(f"frozen input drift: {name} expected={record['sha256']} actual={actual}")
    genesis = json.loads(_resolve(protocol["inputs"]["genesis_audit"]["path"]).read_text(encoding="utf-8"))
    observed = genesis["development"]["summary_40bps"]
    if not np.isclose(observed["active_mean"], -0.005680251324765568, rtol=0, atol=1e-15):
        raise RuntimeError("momentum genesis effect drift")
    return protocol


def rank_momentum_signal(surface: pd.DataFrame) -> pd.DataFrame:
    """Use the identical neutralization but rank the positive residual first."""

    neutralized = core.rank_reversal_signal(surface)
    rows = []
    for _, week in neutralized.groupby("decision_dt", sort=True, observed=True):
        week = week.sort_values(["residual_return_5obs", "symbol"], ascending=[False, True], kind="mergesort").copy()
        week["momentum_rank"] = np.arange(1, len(week) + 1, dtype=np.int64)
        rows.append(week.drop(columns="reversal_rank"))
    return pd.concat(rows, ignore_index=True)


def _jsonable(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_jsonable(item) for item in value]
    if isinstance(value, (np.bool_, bool)):
        return bool(value)
    if isinstance(value, (np.integer, int)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        return None if not np.isfinite(value) else float(value)
    return value


def _pct(value: float | None) -> str:
    return "NA" if value is None or not np.isfinite(value) else f"{value * 100:.3f}%"


