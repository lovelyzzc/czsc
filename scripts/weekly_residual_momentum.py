def main() -> None:
    """Run the exact post-development sign on the locked temporal split."""

    protocol = load_and_verify_protocol()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    blind = rank_momentum_signal(core.build_blind_surface(protocol))
    blind.to_parquet(OUTPUT_DIR / protocol["outputs"]["blind_ranked_signal"], index=False)
    memberships = core.build_memberships(blind, rank_column="momentum_rank")
    memberships.to_parquet(OUTPUT_DIR / protocol["outputs"]["memberships"], index=False)
    val_end = pd.Timestamp(protocol["sample"]["validation"][1])
    weekly = core.build_weekly_outcomes(protocol, memberships, end_date=val_end, terminal_liquidation=True)
    weekly.to_parquet(OUTPUT_DIR / protocol["outputs"]["weekly"], index=False)
    dev_start = pd.Timestamp(protocol["sample"]["development"][0])
    dev_end = pd.Timestamp(protocol["sample"]["development"][1])
    val_start = pd.Timestamp(protocol["sample"]["validation"][0])
    dev_summaries = {
        bps: core.summarize_segment(
            weekly,
            protocol,
            dev_start,
            dev_end,
            bps=bps,
            halves=protocol["sample"]["development_halves"],
        )
        for bps in (20, 40, 60)
    }
    val_summaries = {
        bps: core.summarize_segment(
            weekly,
            protocol,
            val_start,
            val_end,
            bps=bps,
            halves=protocol["sample"]["validation_halves"],
        )
        for bps in (20, 40, 60)
    }
    val_gate = core.evaluate_gate(val_summaries[40], protocol)
    stress_checks = {
        "validation_60bps_active_mean_positive": val_summaries[60]["active_mean"] > 0,
        "validation_60bps_bootstrap_q05_positive": val_summaries[60]["bootstrap"]["q05"] > 0,
    }
    stress_gate = {"passed": all(stress_checks.values()), "checks": stress_checks}
    passed = bool(val_gate["passed"] and stress_gate["passed"])
    audit: dict[str, Any] = {
        "study_id": protocol["study_id"],
        "protocol_sha256": sha256_file(PROTOCOL_PATH),
        "blind_signal_rows": int(len(blind)),
        "membership_rows": int(len(memberships)),
        "development_is_confirmatory": False,
        "development_descriptive": {
            "summary_20bps": dev_summaries[20],
            "summary_40bps": dev_summaries[40],
            "summary_60bps": dev_summaries[60],
        },
        "locked_validation": {
            "summary_20bps": val_summaries[20],
            "summary_40bps": val_summaries[40],
            "summary_60bps": val_summaries[60],
            "gate": val_gate,
        },
        "cost_stress": stress_gate,
        "live_trading_authorized": False,
        "status": (
            "RETROSPECTIVE_MOMENTUM_CANDIDATE_DAILY_PATH_AND_FORWARD_TEST_REQUIRED"
            if passed
            else "HYPOTHESIS_FALSIFIED_LOCKED_VALIDATION"
        ),
        "conclusion": (
            "锁定验证和 60bp 成本压力均通过；下一步必须构建严格日频自融资路径，并重新进入独立前向测试。"
            if passed
            else "锁定验证或 60bp 成本压力失败；该精确短期动量策略被否决，不做参数救援。"
        ),
    }
    audit = _jsonable(audit)
    (OUTPUT_DIR / protocol["outputs"]["audit"]).write_text(
        json.dumps(audit, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    write_report(audit)
    print(json.dumps({"status": audit["status"]}, ensure_ascii=False))


if __name__ == "__main__":
    main()
